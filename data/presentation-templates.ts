export type PresentationStarterTemplate = Pick<
  PresentationProjectRecord,
  | "id"
  | "name"
  | "description"
  | "themeId"
  | "accentColor"
  | "backgroundColor"
  | "textColor"
  | "slides"
> & { useCase: string };

function starter(
  id: string,
  name: string,
  description: string,
  useCase: string,
  themeId: PresentationThemeId,
  slides: PresentationSlide[],
): PresentationStarterTemplate {
  const theme = presentationThemes.find((item) => item.id === themeId) ?? presentationThemes[0];
  return {
    id,
    name,
    description,
    useCase,
    themeId,
    accentColor: theme.accentColor,
    backgroundColor: theme.backgroundColor,
    textColor: theme.textColor,
    slides,
  };
}

